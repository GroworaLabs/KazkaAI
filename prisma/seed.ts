import { PrismaClient } from "@prisma/client";

const prisma = new PrismaClient();

async function main() {
  console.log("🌱 Seeding database...");

  const demo = await prisma.story.upsert({
    where: { shareToken: "demo-story-token" },
    update: {},
    create: {
      childName: "Соломія",
      childAge: 5,
      theme: "єдиноріг",
      shareToken: "demo-story-token",
      content: `Жила-була дівчинка на ім'я Соломія, якій щойно виповнилося п'ять років. Вона мешкала на краю чарівного лісу, де між деревами мерехтіли срібні промені місяця.

Одного вечора Соломія почула тихеньке іржання за вікном. Вона визирнула і побачила маленького єдинорога з рожевою гривою, який заплутався у гілках малинника.

— Не бійся, — сказала Соломія і обережно вийшла надвір. — Я допоможу тобі.

Крок за кроком вона розплутала гілки, розмовляючи з єдинорогом тихим голосом, щоб він не злякався. Нарешті тваринка вільно вийшла на галявину й затанцювала від радості, а її ріг засяяв усіма кольорами веселки.

— Ти врятувала мене, — промовив єдиноріг людською мовою. — Як мені відплатити тобі?

— Покатай мене по зоряному небу, — попросила Соломія.

І вони злетіли вгору — над лісом, над хмарами, до самих зірок. Соломія сміялась від щастя, а зірки ловила долоньками.

Коли вони повернулись додому, мама вже чекала з теплим молоком і книжкою казок. Єдиноріг торкнувся чолом до Соломіїної щоки, залишив там золоту зірочку й зник у лісі.

Соломія лягла спати з усмішкою, знаючи: той, хто допомагає іншим, завжди отримує найбільшу нагороду — справжній друг.`,
    },
  });

  console.log(`✅ Demo story created: ${demo.id}`);
  console.log("🌱 Seeding complete.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
